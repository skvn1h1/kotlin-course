// ============================================================
// Задача 24. Характеристика числовой коллекции.
// Принимает коллекцию чисел и возвращает строку-характеристику.
// Ветви when проверяются СВЕРХУ ВНИЗ, поэтому порядок условий
// повторяет порядок из условия задачи — сработает первая подходящая.
// ============================================================
fun describeCollection(numbers: List<Int>): String {
    return when {
        numbers.isEmpty() -> "Пусто"
        numbers.size < 5 -> "Короткая"
        numbers.first() == 0 -> "Стартовая"
        numbers.sum() > 10000 -> "Массивная"
        numbers.average() == 10.0 -> "Сбалансированная"
        numbers.joinToString("").length == 20 -> "Клейкая"
        (numbers.maxOrNull() ?: 0) < -10 -> "Отрицательная"
        (numbers.minOrNull() ?: 0) > 1000 -> "Положительная"
        3 in numbers && 14 in numbers -> "Пи***тая"
        else -> "Уникальная"
    }
}

// ============================================================
// Задача 25. Анализ учебных оценок.
// Каждый метод работает с результатом предыдущего (цепочка вызовов):
// фильтруем оценки >= 60 -> сортируем по возрастанию -> берём первые 3.
// ============================================================
fun getTopGrades(grades: List<Int>): List<Int> {
    return grades
        .filter { it >= 60 }   // 1) оставляем только удовлетворительные оценки
        .sorted()              // 2) сортируем оставшиеся по возрастанию
        .take(3)               // 3) берём первые 3
}

// ============================================================
// Задача 26. Создание каталога по первой букве.
// Приводим все слова к нижнему регистру и группируем по первой букве.
// ============================================================
fun createCatalog(items: List<String>): Map<Char, List<String>> {
    return items
        .map { it.lowercase() }   // 1) все слова в нижний регистр
        .groupBy { it.first() }   // 2) группируем по первой букве
}

// ============================================================
// Задание 27. Подсчёт средней длины слов в списке.
// Переводим слова в количество букв, считаем среднее и форматируем
// результат до двух знаков после запятой (шаблон "%.2f").
// ============================================================
fun getAverageWordLength(items: List<String>): String {
    val averageLength = items
        .map { it.length }   // слово -> количество букв
        .average()           // среднее значение
    return "Средняя длина слова: %.2f".format(averageLength)
}

// ============================================================
// Задание 28. Категоризация чисел.
// Убираем дубли, сортируем по убыванию и делим на чётные/нечетные.
// ============================================================
fun categorizeNumbers(numbers: List<Int>): Map<String, List<Int>> {
    return numbers
        .distinct()          // 1) только уникальные числа
        .sortedDescending()  // 2) сортировка по убыванию
        .groupBy { if (it % 2 == 0) "четные" else "нечетные" }  // 3) деление по чётности
}

// ============================================================
// Задание 29. Поиск первого подходящего элемента.
// Ищем первый возраст, который больше переданного числа.
// Возвращаем Int? — если ничего не нашли, вернётся null.
// ============================================================
fun findFirstOverAge(ages: List<Int?>, olderThan: Int): Int? {
    return ages
        .filterNotNull()                 // убираем null, чтобы спокойно сравнивать числа
        .firstOrNull { it > olderThan }  // первый подходящий элемент или null
}
